package action

import (
	"errors"
	"sort"
	"strconv"
	"strings"
	"time"

	"github.com/hortonworks/cloud-haunter/config"
	"github.com/hortonworks/cloud-haunter/types"
	"github.com/hortonworks/cloud-haunter/utils"
	log "github.com/sirupsen/logrus"
)

const unknownOwner = "???"

// NewBudgetNotification returns the budget-notification action implementation.
func NewBudgetNotification(cfg *config.Config) types.Action {
	return budgetNotificationAction{cfg: cfg, now: time.Now}
}

type budgetNotificationAction struct {
	cfg *config.Config
	now func() time.Time
}

type mergedCosts struct {
	byOwner    map[string]float64
	byResource map[string]float64
}

func (a budgetNotificationAction) Execute(op types.OpType, filters []types.FilterType, items []types.CloudItem) error {
	since, until := a.budgetWindow()
	log.Infof("[BUDGET_NOTIFICATION] Checking %d items generated by operation %s and filters %s against a limit of %.2f from %s until %s",
		len(items), op, filters, a.cfg.BudgetLimit, since.Format(time.DateOnly), until.Format(time.DateOnly))
	a.warnAboutUncountedAwsSpend(items)
	costs, costErr := a.collectIgnoredCosts(since, until)
	report := a.buildReport(until.Sub(since), a.groupByOwner(items), costs)
	logReport(report)
	if len(report.Owners) == 0 {
		log.Info("[BUDGET_NOTIFICATION] Nobody exceeds the budget limit, nothing to send")
		return costErr
	}
	return errors.Join(costErr, a.dispatch(report))
}

// budgetWindow covers the whole UTC days of the budget period before today, so every cloud sums the same days
func (a budgetNotificationAction) budgetWindow() (since, until time.Time) {
	until = startOfUTCDay(a.now())
	return startOfUTCDay(until.Add(-a.cfg.BudgetPeriod)), until
}

func startOfUTCDay(moment time.Time) time.Time {
	year, month, day := moment.UTC().Date()
	return time.Date(year, month, day, 0, 0, 0, 0, time.UTC)
}

func (a budgetNotificationAction) warnAboutUncountedAwsSpend(items []types.CloudItem) {
	for _, item := range a.awsItemsWithEmptyIgnoreLabel(items) {
		log.Warnf("[BUDGET_NOTIFICATION] The %s label of %s %s on AWS has no value, Cost Explorer cannot count its spend until the label gets one",
			a.cfg.IgnoreLabel, item.GetType(), item.GetName())
	}
}

// awsItemsWithEmptyIgnoreLabel finds the items whose spend Cost Explorer reports as untagged, because it groups an empty tag value with a missing tag
func (a budgetNotificationAction) awsItemsWithEmptyIgnoreLabel(items []types.CloudItem) []types.CloudItem {
	var uncounted []types.CloudItem
	for _, item := range items {
		if value, labelled := item.GetTags()[a.cfg.IgnoreLabel]; item.GetCloudType() == types.AWS && labelled && value == "" {
			uncounted = append(uncounted, item)
		}
	}
	return uncounted
}

func (a budgetNotificationAction) collectIgnoredCosts(since, until time.Time) (mergedCosts, error) {
	costs := mergedCosts{byOwner: map[string]float64{}, byResource: map[string]float64{}}
	var errs []error
	for cloud, getProvider := range a.cfg.CloudProviders {
		costProvider, reportsCost := getProvider().(types.CostProvider)
		if !reportsCost {
			log.Warnf("[BUDGET_NOTIFICATION] %s does not report costs, its owners are not reminded", cloud)
			continue
		}
		cloudCosts, err := costProvider.GetIgnoredCosts(since, until)
		if err != nil {
			log.Errorf("[BUDGET_NOTIFICATION] Failed to fetch the ignored costs of %s, its spend is left out, err: %s", cloud, err.Error())
			errs = append(errs, err)
			continue
		}
		log.Infof("[BUDGET_NOTIFICATION] %s reported the ignored spend of %d owners and the cost of %d resources", cloud, len(cloudCosts.ByOwner), len(cloudCosts.ByResource))
		for owner, spend := range cloudCosts.ByOwner {
			costs.byOwner[utils.NormalizeOwner(owner)] += spend
		}
		for resourceID, spend := range cloudCosts.ByResource {
			costs.byResource[strings.ToLower(resourceID)] += spend
		}
	}
	return costs, errors.Join(errs...)
}

func (a budgetNotificationAction) groupByOwner(items []types.CloudItem) map[string][]types.CloudItem {
	itemsByOwner := map[string][]types.CloudItem{}
	for _, item := range items {
		rawOwner := billingOwner(item)
		owner := utils.NormalizeOwner(rawOwner)
		switch {
		case owner == "":
			log.Warnf("[BUDGET_NOTIFICATION] Skipping %s %s on %s, it has no owner to remind", item.GetType(), item.GetName(), item.GetCloudType())
		case a.isExcludedOwner(rawOwner, item.GetCloudType()):
			log.Debugf("[BUDGET_NOTIFICATION] Skipping %s %s on %s, its owner %s is excluded", item.GetType(), item.GetName(), item.GetCloudType(), rawOwner)
		default:
			itemsByOwner[owner] = append(itemsByOwner[owner], item)
		}
	}
	return itemsByOwner
}

// isExcludedOwner applies the excludeInstance owners of the filter config to the billing owner, which the
// nomatch filter cannot do for the items that only inherit their owner from an Azure resource group
func (a budgetNotificationAction) isExcludedOwner(owner string, cloud types.CloudType) bool {
	if a.cfg.FilterConfig == nil {
		return false
	}
	excludedOwners := a.cfg.FilterConfig.GetFilterValues(types.ExcludeInstance, cloud, types.Owner)
	if a.cfg.ExactMatchOwner {
		return utils.IsAnyEquals(owner, excludedOwners...)
	}
	return utils.IsStartsWith(owner, excludedOwners...)
}

func billingOwner(item types.CloudItem) string {
	if owner := item.GetOwner(); owner != "" && owner != unknownOwner {
		return owner
	}
	return types.GetItemMetadata(item)[types.ResourceGroupOwnerMetadata]
}

func (a budgetNotificationAction) buildReport(period time.Duration, itemsByOwner map[string][]types.CloudItem, costs mergedCosts) *types.BudgetReport {
	report := &types.BudgetReport{Period: period, Limit: a.cfg.BudgetLimit}
	for owner, items := range itemsByOwner {
		spend := costs.byOwner[owner]
		if spend <= a.cfg.BudgetLimit {
			log.Debugf("[BUDGET_NOTIFICATION] %s has %d long-running ignored items but spent only %.2f", owner, len(items), spend)
			continue
		}
		report.Owners = append(report.Owners, types.OwnerSpend{Owner: owner, Spend: spend, Items: withCosts(items, costs.byResource)})
	}
	sort.Slice(report.Owners, func(i, j int) bool { return report.Owners[i].Spend > report.Owners[j].Spend })
	return report
}

func withCosts(items []types.CloudItem, costByResource map[string]float64) []types.CostedItem {
	costedItems := make([]types.CostedItem, 0, len(items))
	for _, item := range items {
		costedItem := types.CostedItem{Item: item}
		if cost, known := costByResource[strings.ToLower(types.GetItemID(item))]; known {
			costedItem.Cost = &cost
		}
		costedItems = append(costedItems, costedItem)
	}
	sort.SliceStable(costedItems, func(i, j int) bool { return costsMore(costedItems[i], costedItems[j]) })
	return costedItems
}

func costsMore(first, second types.CostedItem) bool {
	switch {
	case first.Cost == nil:
		return false
	case second.Cost == nil:
		return true
	default:
		return *first.Cost > *second.Cost
	}
}

func logReport(report *types.BudgetReport) {
	for _, owner := range report.Owners {
		log.Infof("[BUDGET_NOTIFICATION] %s spent %.2f on ignore-labelled resources in the last %s and has %d long-running ignored items",
			owner.Owner, owner.Spend, report.Period, len(owner.Items))
		for _, costedItem := range owner.Items {
			item := costedItem.Item
			log.Infof("[BUDGET_NOTIFICATION]   [%s] %s %s cost: %s", item.GetCloudType(), item.GetType(), item.GetName(), formatCost(costedItem.Cost))
		}
	}
}

func formatCost(cost *float64) string {
	if cost == nil {
		return "unknown"
	}
	return strconv.FormatFloat(*cost, 'f', 2, 64)
}

func (a budgetNotificationAction) dispatch(report *types.BudgetReport) error {
	var errs []error
	for name, dispatcher := range a.cfg.Dispatchers {
		budgetDispatcher, deliversBudgetReports := dispatcher.(types.BudgetDispatcher)
		if !deliversBudgetReports {
			log.Debugf("[BUDGET_NOTIFICATION] %s cannot deliver budget reports", name)
			continue
		}
		if err := budgetDispatcher.SendBudgetReport(report); err != nil {
			log.Errorf("[%s] Failed to send the budget report, err: %s", name, err.Error())
			errs = append(errs, err)
		}
	}
	return errors.Join(errs...)
}
